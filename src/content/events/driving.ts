function pass(c: Ctx, faults: number) {
  c.flag('driver');
  c.happy(8);
  const officer = faults === 0 ? 'افسر گفت «آفرین! عین راننده‌ی اتوبوس واحد!»' : faults === 1 ? 'افسر گفت «بد نبود، ولی یه کم بیشتر تمرین کن.»' : 'افسر کلی غر زد ولی آخرش امضا کرد!';
  return `گواهینامه‌ات رو گرفتی! ${officer}`;
}
